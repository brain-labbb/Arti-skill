class VerificationError(RuntimeError):
    """Raised for a fail-closed output-contract violation."""


@dataclass(frozen=True)
class VerifierConfig:
    """Pins and paths; tests may use a deliberately small local cohort."""

    source_records: Path = DEFAULT_SOURCE_RECORDS
    source_manifest: Path = DEFAULT_SOURCE_MANIFEST
    sample_size: int = EXPECTED_SAMPLE_SIZE
    joint_count: int = EXPECTED_JOINT_COUNT
    source_records_sha256: str | None = EXPECTED_SOURCE_RECORDS_SHA256
    source_manifest_sha256: str | None = EXPECTED_SOURCE_MANIFEST_SHA256
    source_manifest_content_sha256: str | None = EXPECTED_SOURCE_MANIFEST_CONTENT_SHA256
    ordered_asset_keys_sha256: str | None = EXPECTED_ORDERED_ASSET_KEYS_SHA256


@dataclass(frozen=True)
class SourceCohort:
    records_by_rank: Mapping[int, dict[str, Any]]
    manifest_records_by_rank: Mapping[int, dict[str, Any]]
    joints_by_key: Mapping[tuple[str, str], dict[str, Any]]
    joint_order: Mapping[tuple[str, str], int]
    ordered_keys_sha256: str
    records_sha256: str
    manifest_sha256: str
    manifest_content_sha256: str


def canonical_json(value: Any) -> str:
    """Canonical JSON used by the historical LAM Table-3/Table-4 code."""

    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True)


def canonical_sha256(value: Any) -> str:
    return hashlib.sha256(canonical_json(value).encode("utf-8")).hexdigest()


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with regular_file(path).open("rb") as stream:
        for block in iter(lambda: stream.read(4 * 1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _reject_json_constant(value: str) -> None:
    raise VerificationError(f"non-finite JSON constant is forbidden: {value}")


def _no_duplicate_object(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise VerificationError(f"duplicate JSON key: {key!r}")
        result[key] = value
    return result


def strict_json_loads(text: str, *, context: str) -> Any:
    try:
        return json.loads(
            text,
            object_pairs_hook=_no_duplicate_object,
            parse_constant=_reject_json_constant,
        )
    except (json.JSONDecodeError, TypeError, VerificationError) as exc:
        raise VerificationError(f"invalid JSON in {context}: {exc}") from exc


def regular_file(path: Path) -> Path:
    if not path.exists():
        raise VerificationError(f"missing required file: {path}")
    if path.is_symlink() or not path.is_file():
        raise VerificationError(f"required file is not a regular non-symlink: {path}")
    return path.resolve()


def regular_dir(path: Path) -> Path:
    if not path.exists():
        raise VerificationError(f"missing output directory: {path}")
    if path.is_symlink() or not path.is_dir():
        raise VerificationError(f"output root is not a regular non-symlink directory: {path}")
    return path.resolve()


def read_json(path: Path) -> Any:
    return strict_json_loads(regular_file(path).read_text(encoding="utf-8"), context=str(path))


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    with regular_file(path).open("r", encoding="utf-8", newline="") as stream:
        for line_number, line in enumerate(stream, 1):
            if not line.strip():
                continue
            value = strict_json_loads(line, context=f"{path}:{line_number}")
            if not isinstance(value, dict):
                raise VerificationError(f"JSONL row is not an object: {path}:{line_number}")
            rows.append(value)
    return rows


def atomic_json(path: Path, value: Any) -> None:
    """Write only the verifier receipt, atomically, after checks finish."""

    path.parent.mkdir(parents=True, exist_ok=True)
    encoded = json.dumps(value, indent=2, sort_keys=True, ensure_ascii=True) + "\n"
    descriptor, temporary_name = tempfile.mkstemp(
        prefix=f".{path.name}.", suffix=".tmp", dir=str(path.parent)
    )
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(encoded)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary_name, path)
    finally:
        try:
            os.unlink(temporary_name)
        except FileNotFoundError:
            pass


def _expect_dict(value: Any, label: str) -> dict[str, Any]:
    if not isinstance(value, dict):
        raise VerificationError(f"{label} must be an object")
    return value


def _expect_list(value: Any, label: str) -> list[Any]:
    if not isinstance(value, list):
        raise VerificationError(f"{label} must be a list")
    return value


def _expect_int(value: Any, label: str, *, minimum: int | None = None) -> int:
    if isinstance(value, bool) or not isinstance(value, int):
        raise VerificationError(f"{label} must be an integer")
    if minimum is not None and value < minimum:
        raise VerificationError(f"{label} must be >= {minimum}")
    return value


def _expect_number(value: Any, label: str, *, allow_negative: bool = True) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise VerificationError(f"{label} must be a finite number")
    result = float(value)
    if not math.isfinite(result):
        raise VerificationError(f"{label} must be finite")
    if not allow_negative and result < 0.0:
        raise VerificationError(f"{label} must be non-negative")
    return result


def _expect_bool(value: Any, label: str) -> bool:
    if not isinstance(value, bool):
        raise VerificationError(f"{label} must be boolean")
    return value


def _require_same(actual: Any, expected: Any, label: str) -> None:
    if actual != expected:
        raise VerificationError(f"{label} mismatch: expected {expected!r}, observed {actual!r}")


def _manifest_self_hash(manifest: dict[str, Any]) -> str:
    payload = dict(manifest)
    payload.pop("manifest_content_sha256", None)
    return canonical_sha256(payload)


def _source_identity_fields() -> tuple[str, ...]:
    return (
        "asset_key",
        "selection_rank",
        "selection_hash",
        "tier",
        "category",
        "object_release_id",
        "rel_path",
        "urdf_sha256",
    )


def _source_manifest_identity_fields() -> tuple[str, ...]:
    return _source_identity_fields()


def _build_source_cohort(config: VerifierConfig) -> SourceCohort:
    source_records_path = regular_file(config.source_records)
    source_manifest_path = regular_file(config.source_manifest)
    records_sha = sha256_file(source_records_path)
    manifest_sha = sha256_file(source_manifest_path)
    if config.source_records_sha256 is not None:
        _require_same(records_sha, config.source_records_sha256, "Table-3 source JSONL SHA256")
    if config.source_manifest_sha256 is not None:
        _require_same(manifest_sha, config.source_manifest_sha256, "Table-3 source manifest file SHA256")

    manifest = _expect_dict(read_json(source_manifest_path), "Table-3 source manifest")
    manifest_content_sha = manifest.get("manifest_content_sha256")
    if not isinstance(manifest_content_sha, str):
        raise VerificationError("Table-3 source manifest lacks manifest_content_sha256")
    _require_same(_manifest_self_hash(manifest), manifest_content_sha, "Table-3 source manifest self hash")
    if config.source_manifest_content_sha256 is not None:
        _require_same(
            manifest_content_sha,
            config.source_manifest_content_sha256,
            "Table-3 source manifest content SHA256",
        )

    source_rows = read_jsonl(source_records_path)
    if len(source_rows) != config.sample_size:
        raise VerificationError(
            f"Table-3 source record count is {len(source_rows)}, expected {config.sample_size}"
        )
    records_by_rank: dict[int, dict[str, Any]] = {}
    keys: set[str] = set()
    for row in source_rows:
        rank = _expect_int(row.get("selection_rank"), "source selection_rank", minimum=1)
        key = row.get("asset_key")
        if not isinstance(key, str) or not key:
            raise VerificationError("source asset_key is missing")
        if rank in records_by_rank or key in keys:
            raise VerificationError("source Table-3 rows have duplicate rank or asset_key")
        _require_same(
            row.get("manifest_content_sha256"),
            manifest_content_sha,
            f"source record manifest binding for rank {rank}",
        )
        records_by_rank[rank] = row
        keys.add(key)
    expected_ranks = set(range(1, config.sample_size + 1))
    if set(records_by_rank) != expected_ranks:
        raise VerificationError("source Table-3 ranks are not exactly 1..N")

    manifest_records = _expect_list(manifest.get("records"), "Table-3 manifest.records")
    if len(manifest_records) != config.sample_size:
        raise VerificationError("Table-3 manifest record count is not N")
    manifest_by_rank: dict[int, dict[str, Any]] = {}
    for item in manifest_records:
        item = _expect_dict(item, "Table-3 manifest record")
        rank = _expect_int(item.get("selection_rank"), "Table-3 manifest selection_rank", minimum=1)
        if rank in manifest_by_rank:
            raise VerificationError("duplicate Table-3 manifest selection_rank")
        manifest_by_rank[rank] = item
    if set(manifest_by_rank) != expected_ranks:
        raise VerificationError("Table-3 manifest ranks are not exactly 1..N")

    joints_by_key: dict[tuple[str, str], dict[str, Any]] = {}
    joint_order: dict[tuple[str, str], int] = {}
    ordered_keys: list[str] = []
    ordinal = 0
    for rank in range(1, config.sample_size + 1):
        row = records_by_rank[rank]
        item = manifest_by_rank[rank]
        for field in _source_identity_fields():
            _require_same(item.get(field), row.get(field), f"Table-3 manifest/source {field} rank {rank}")
        ordered_keys.append(str(row["asset_key"]))
        source_joints = _expect_list(row.get("joints"), f"source joints rank {rank}")
        for joint in source_joints:
            joint = _expect_dict(joint, f"source joint rank {rank}")
            name = joint.get("joint_name")
            if not isinstance(name, str) or not name:
                raise VerificationError(f"source joint has no name at rank {rank}")
            joint_key = (str(row["asset_key"]), name)
            if joint_key in joints_by_key:
                raise VerificationError(f"duplicate source joint identity {joint_key!r}")
            joints_by_key[joint_key] = joint
            joint_order[joint_key] = ordinal
            ordinal += 1
    if len(joints_by_key) != config.joint_count:
        raise VerificationError(
            f"Table-3 source movable-joint count is {len(joints_by_key)}, expected {config.joint_count}"
        )
    ordered_hash = canonical_sha256(ordered_keys)
    source_selection = _expect_dict(manifest.get("selection"), "Table-3 manifest.selection")
    _require_same(
        source_selection.get("selected_asset_keys_sha256"),
        ordered_hash,
        "Table-3 manifest selected-asset hash",
    )
    if config.ordered_asset_keys_sha256 is not None:
        _require_same(ordered_hash, config.ordered_asset_keys_sha256, "pinned ordered asset-key SHA256")
    return SourceCohort(
        records_by_rank=records_by_rank,
        manifest_records_by_rank=manifest_by_rank,
        joints_by_key=joints_by_key,
        joint_order=joint_order,
        ordered_keys_sha256=ordered_hash,
        records_sha256=records_sha,
        manifest_sha256=manifest_sha,
        manifest_content_sha256=manifest_content_sha,
    )


def _manifest_source(manifest: dict[str, Any]) -> dict[str, Any]:
    source = manifest.get("source")
    return _expect_dict(source, "frozen_manifest.source")


def _validate_code_identity(manifest: Mapping[str, Any]) -> None:
    """Bind formal output to the exact evaluator modules used at freeze."""

    expected_paths = {
        "runner": REPO / "exp/scripts/run_urdf_lam_supplementary_v1.py",
        "static": REPO / "exp/scripts/lam_supplementary_static.py",
        "geometry": REPO / "exp/scripts/lam_supplementary_geometry.py",
        "verifier": SCRIPT,
    }
    identity = _expect_dict(manifest.get("code_identity"), "frozen code_identity")
    if set(identity) != set(expected_paths):
        raise VerificationError("frozen code_identity must name runner/static/geometry/verifier exactly")
    for name, expected_path in expected_paths.items():
        resolved = regular_file(expected_path)
        entry = _expect_dict(identity.get(name), f"frozen code_identity.{name}")
        if set(entry) != {"path", "sha256"}:
            raise VerificationError(f"frozen code_identity.{name} has unexpected fields")
        _require_same(entry.get("path"), str(resolved), f"frozen code_identity.{name} path")
        _require_same(entry.get("sha256"), sha256_file(resolved), f"frozen code_identity.{name} SHA256")


def _value_from_any(mapping: Mapping[str, Any], names: Sequence[str], label: str) -> Any:
    observed = [(name, mapping[name]) for name in names if name in mapping]
    if not observed:
        raise VerificationError(f"missing {label}; expected one of {', '.join(names)}")
    values = {canonical_json(value) for _, value in observed}
    if len(values) != 1:
        raise VerificationError(f"conflicting aliases for {label}")
    return observed[0][1]


def _validate_manifest(
    root: Path, manifest: dict[str, Any], source: SourceCohort, config: VerifierConfig
) -> tuple[dict[int, dict[str, Any]], str, dict[str, Any]]:
    _require_same(_manifest_self_hash(manifest), manifest.get("manifest_content_sha256"), "frozen manifest self hash")
    _require_same(_expect_int(manifest.get("sample_size"), "frozen manifest sample_size"), config.sample_size, "frozen sample size")
    _require_same(
        _expect_int(
            _value_from_any(
                manifest, ("joint_count", "expected_joint_count", "j_eval"), "frozen joint count"
            ),
            "frozen joint count",
        ),
        config.joint_count,
        "frozen joint count",
    )
    if bool(manifest.get("qualification_smoke")):
        raise VerificationError("formal N=800 verifier rejects qualification_smoke manifests")
    protocol_id = manifest.get("protocol_id")
    if not isinstance(protocol_id, str) or not protocol_id or protocol_id.lower() == "tbd":
        raise VerificationError("frozen manifest has no final protocol_id")
    runtime_binding = _validate_genesis_binding(manifest)
    _validate_code_identity(manifest)
    _validate_strict_state_protocol(manifest, source, config)
    source_meta = _manifest_source(manifest)
    _require_same(
        _value_from_any(
            source_meta,
            ("table3_asset_records_sha256", "source_asset_records_sha256"),
            "source asset-records SHA256",
        ),
        source.records_sha256,
        "frozen source asset-records SHA256",
    )
    _require_same(
        _value_from_any(
            source_meta,
            ("table3_manifest_sha256", "source_manifest_sha256"),
            "source manifest file SHA256",
        ),
        source.manifest_sha256,
        "frozen source manifest file SHA256",
    )
    _require_same(
        _value_from_any(
            source_meta,
            ("table3_manifest_content_sha256", "source_manifest_content_sha256"),
            "source manifest content SHA256",
        ),
        source.manifest_content_sha256,
        "frozen source manifest content SHA256",
    )
    _require_same(
        _value_from_any(
            manifest,
            ("ordered_selected_asset_keys_sha256", "selected_asset_keys_sha256"),
            "ordered selected asset-key SHA256",
        ),
        source.ordered_keys_sha256,
        "frozen selected asset-key SHA256",
    )
    snapshot = regular_file(root / "protocol_snapshot.md")
    snapshot_sha = sha256_file(snapshot)
    expected_snapshot_sha = _value_from_any(
        source_meta,
        ("protocol_snapshot_sha256", "protocol_document_sha256_at_freeze"),
        "protocol snapshot SHA256",
    )
    _require_same(snapshot_sha, expected_snapshot_sha, "protocol snapshot SHA256")
    if not snapshot.read_text(encoding="utf-8").strip():
        raise VerificationError("protocol_snapshot.md is empty")

    fields = _expect_list(manifest.get("input_identity_fields"), "frozen input_identity_fields")
    if not fields or not all(isinstance(field, str) and field for field in fields):
        raise VerificationError("frozen input_identity_fields must be a non-empty string list")
    items_raw = _expect_list(manifest.get("items"), "frozen manifest.items")
    if len(items_raw) != config.sample_size:
        raise VerificationError("frozen manifest item count is not N")
    items: dict[int, dict[str, Any]] = {}
    for item_raw in items_raw:
        item = _expect_dict(item_raw, "frozen manifest item")
        rank = _expect_int(item.get("selection_rank"), "frozen item selection_rank", minimum=1)
        if rank in items:
            raise VerificationError("duplicate frozen manifest selection_rank")
        source_row = source.records_by_rank.get(rank)
        source_manifest_row = source.manifest_records_by_rank.get(rank)
        if source_row is None or source_manifest_row is None:
            raise VerificationError(f"frozen item references unknown source rank {rank}")
        for field in _source_identity_fields():
            _require_same(item.get(field), source_row.get(field), f"frozen item {field} rank {rank}")
        _require_same(
            item.get("source_record_sha256"), canonical_sha256(source_row), f"frozen source-record hash rank {rank}"
        )
        _require_same(
            item.get("source_manifest_record_sha256"),
            canonical_sha256(source_manifest_row),
            f"frozen source-manifest-record hash rank {rank}",
        )
        expected_identity = canonical_sha256({field: item.get(field) for field in fields})
        _require_same(item.get("input_identity_sha256"), expected_identity, f"frozen input identity rank {rank}")
        items[rank] = item
    if set(items) != set(range(1, config.sample_size + 1)):
        raise VerificationError("frozen manifest ranks are not exactly 1..N")
    _require_same(
        manifest.get("items_sha256"), canonical_sha256([items[index] for index in range(1, config.sample_size + 1)]),
        "frozen manifest items SHA256",
    )
    _validate_lam_s1_registries(manifest)
    return items, protocol_id, runtime_binding


def _empty_registry(manifest: Mapping[str, Any], names: Sequence[str], label: str) -> None:
    registries = manifest.get("registries", {})
    if registries is not None and not isinstance(registries, dict):
        raise VerificationError("frozen manifest.registries must be an object")
    candidates: list[Any] = []
    for container in (manifest, registries if isinstance(registries, dict) else {}):
        for name in names:
            if name in container:
                candidates.append(container[name])
    if not candidates:
        raise VerificationError(f"frozen manifest must explicitly declare {label}")
    for registry in candidates:
        if not isinstance(registry, list) or registry:
            raise VerificationError(f"LAM {label} must be an explicitly empty list")


def _validate_lam_s1_registries(manifest: Mapping[str, Any]) -> None:
    _empty_registry(
        manifest,
        ("release_mechanical_receipt_registry", "release_receipt_registry"),
        "release receipt registry",
    )
    _empty_registry(
        manifest,
        ("method_specific_allowance_registry", "allowance_registry"),
        "method-specific allowance registry",
    )


def _validate_genesis_binding(manifest: Mapping[str, Any]) -> dict[str, Any]:
    """Require the new LAM run to be Genesis contact-penetration, never PyBullet."""

    _require_same(
        manifest.get("engine_protocol_id"),
        GENESIS_ENGINE_PROTOCOL_ID,
        "frozen Genesis engine protocol",
    )
    binding = manifest.get("runtime_binding")
    engine_runtime = manifest.get("engine_runtime")
    if binding is not None and engine_runtime is not None and binding != engine_runtime:
        raise VerificationError("conflicting frozen runtime_binding and engine_runtime aliases")
    if binding is None:
        binding = engine_runtime
    binding = _expect_dict(binding, "frozen Genesis runtime binding")
    _require_same(binding.get("engine"), "genesis", "frozen runtime engine")
    _require_same(
        binding.get("engine_protocol_id"), GENESIS_ENGINE_PROTOCOL_ID, "frozen runtime engine protocol"
    )
    version = binding.get("genesis_version") or binding.get("version")
    if not isinstance(version, str) or not version.strip():
        raise VerificationError("frozen Genesis runtime lacks a version")
    if "genesis_version" in binding and "version" in binding:
        _require_same(binding.get("genesis_version"), binding.get("version"), "Genesis version aliases")
    scipy_version = binding.get("scipy_version")
    if not isinstance(scipy_version, str) or not scipy_version.strip():
        raise VerificationError("frozen Genesis runtime lacks scipy_version for Sobol replay")
    _require_same(
        binding.get("collision_detection"),
        "contact_penetration",
        "frozen Genesis collision detection",
    )
    threshold = binding.get("penetration_threshold_m")
    if not isinstance(threshold, (int, float)) or isinstance(threshold, bool):
        raise VerificationError("frozen Genesis runtime lacks penetration_threshold_m")
    if not math.isclose(float(threshold), GENESIS_PENETRATION_THRESHOLD_M, rel_tol=0.0, abs_tol=0.0):
        raise VerificationError("frozen Genesis penetration threshold is not 1e-6 m")
    readback_tolerance = binding.get("q_readback_tolerance")
    if (
        isinstance(readback_tolerance, bool)
        or not isinstance(readback_tolerance, (int, float))
        or not math.isclose(float(readback_tolerance), 1e-9, rel_tol=0.0, abs_tol=0.0)
    ):
        raise VerificationError("frozen Genesis q_readback_tolerance is not 1e-9")
    affinity = binding.get("cpu_affinity")
    if (
        not isinstance(affinity, list)
        or not affinity
        or any(isinstance(cpu, bool) or not isinstance(cpu, int) or cpu < 0 for cpu in affinity)
        or affinity != sorted(set(affinity))
    ):
        raise VerificationError("frozen Genesis cpu_affinity must be a sorted non-empty integer list")
    thread_environment = _expect_dict(binding.get("thread_environment"), "frozen Genesis thread environment")
    for key, expected in GENESIS_THREAD_ENV_VALUES.items():
        _require_same(thread_environment.get(key), expected, f"Genesis thread_environment.{key}")
    morph = _expect_dict(binding.get("morph"), "frozen Genesis morph configuration")
    expected_morph = {
        "collision": True,
        "visualization": False,
        "fixed": True,
        "merge_fixed_links": False,
        "convexify": False,
        "decimate": False,
        "watertighten": 0,
        "merge_submeshes_for_collision": False,
        "recompute_inertia": False,
        "align": False,
    }
    for field, expected in expected_morph.items():
        _require_same(morph.get(field), expected, f"Genesis morph.{field}")
    rigid = _expect_dict(binding.get("rigid_options"), "frozen Genesis rigid options")
    for field in ("enable_collision", "enable_self_collision", "enable_neutral_collision", "enable_adjacent_collision"):
        _require_same(rigid.get(field), True, f"Genesis rigid_options.{field}")
    if "contact_pruning_tolerance" in rigid and rigid.get("contact_pruning_tolerance") is not None:
        raise VerificationError("Genesis contact pruning must be disabled for formal results")
    return binding


