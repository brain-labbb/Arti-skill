#!/usr/bin/env python3
"""Independent fail-closed verifier for the LAM supplementary N=800 run.

This verifier deliberately does not import the evaluator.  It binds the new
supplementary run to the immutable Table-3 LAM cohort, checks every terminal
asset/joint/state record, and recomputes the machine-readable aggregate from
those atomic records.  It is intended to be run *after* the evaluator has
written an output root.

Required output-root contract
=============================

``frozen_manifest.json``
    A self-hashed manifest with ``items`` in ``selection_rank`` order, the
    Table-3 source hashes below, ``input_identity_fields`` and empty LAM
    release-receipt / method-allowance registries.
``protocol_snapshot.md``
    The protocol snapshot named and hashed by the frozen manifest.
``asset_records.jsonl``
    Exactly one terminal record for every rank 1..800.  The record has the
    frozen input identity plus static/Table-4b/S1 fields documented in
    :func:`_validate_asset_records`.
``joint_records.jsonl``
    Exactly one terminal record for every Table-3 movable joint (2,395).
``state_records.jsonl`` or state-record shards
    Atomic Table-4a states.  ``state_record_policy=all_intended`` requires all
    21 states per frozen joint; ``executed_only`` is supported only when each
    omitted state is represented fail-closed by its joint record.
``strict_state_records.jsonl``
    Exactly 800 rest states plus 64 scrambled Sobol states for each of the 774
    assets with at least one movable joint (50,336 raw strict states total).
    Zero-DoF assets have no artificial zero-dimensional Sobol rows and fail the
    asset-level strict metric closed.
``summary.json``
    Must contain ``verification_aggregates`` exactly matching the independent
    reaggregation in this file; final results may use COMPLETE, PARTIAL or N/E
    but never TBD.
``report.md``
    Human-readable final report (the verifier checks it is final/non-empty,
    but does not impose a presentation template).

The runner is free to add fields, but may not weaken this contract.  In
particular, receipt evidence generated by the evaluator is never accepted as
a release receipt, and LAM's frozen allowance registry must remain empty.
"""

