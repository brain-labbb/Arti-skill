def _discover_state_paths(root: Path) -> list[Path]:
    monolithic = root / "state_records.jsonl"
    shard_dir = root / "state_records"
    candidates: list[Path] = []
    if monolithic.exists():
        candidates.append(regular_file(monolithic))
    if shard_dir.exists():
        if shard_dir.is_symlink() or not shard_dir.is_dir():
            raise VerificationError("state_records path must be a regular directory")
        candidates.extend(regular_file(path) for path in sorted(shard_dir.glob("*.jsonl")))
    candidates.extend(
        regular_file(path)
        for pattern in ("state_records-*.jsonl", "state_records.part-*.jsonl")
        for path in sorted(root.glob(pattern))
    )
    unique: dict[Path, Path] = {path.resolve(): path for path in candidates}
    candidates = [unique[key] for key in sorted(unique, key=lambda value: value.as_posix())]
    if not candidates:
        raise VerificationError("missing state_records.jsonl or state-record shards")
    if monolithic.exists() and len(candidates) != 1:
        raise VerificationError("state_records.jsonl and shards may not be mixed")
    return candidates


def _terminal(record: Mapping[str, Any], label: str) -> None:
    if record.get("terminal") is not True:
        raise VerificationError(f"{label} lacks terminal=true")
    status = record.get("status")
    if not isinstance(status, str) or status.strip().lower() in TERMINAL_FORBIDDEN:
        raise VerificationError(f"{label} has non-terminal status {status!r}")


def _ordered_rows(
    rows: Sequence[dict[str, Any]], key: Callable[[dict[str, Any]], Any], label: str
) -> None:
    observed = [key(row) for row in rows]
    if observed != sorted(observed):
        raise VerificationError(f"{label} are not deterministically ordered")


def _nonnegative_field(record: Mapping[str, Any], field: str, label: str) -> int:
    return _expect_int(record.get(field), f"{label}.{field}", minimum=0)


def _required_asset_counts(record: Mapping[str, Any], label: str) -> None:
    visual = _nonnegative_field(record, "visual_bearing_link_count", label)
    covered = _nonnegative_field(record, "collision_covered_visual_bearing_link_count", label)
    if covered > visual:
        raise VerificationError(f"{label} collision-covered visual links exceed visual links")
    asset_pass = _expect_bool(
        record.get("visual_bearing_collision_coverage_asset_pass"),
        f"{label}.coverage_asset_pass",
    )
    _require_same(
        asset_pass,
        visual > 0 and covered == visual,
        f"{label} visual-bearing asset pass",
    )
    if "visual_bearing_collision_coverage_complete" in record:
        _expect_bool(record.get("visual_bearing_collision_coverage_complete"), f"{label}.coverage_complete")
    _require_same(
        record.get("visual_bearing_collision_coverage_complete", asset_pass),
        asset_pass,
        f"{label} visual-bearing coverage boolean",
    )
    mass = _nonnegative_field(record, "mass_evaluable_link_count", label)
    placeholder = _nonnegative_field(record, "placeholder_mass_link_count", label)
    if placeholder > mass:
        raise VerificationError(f"{label} placeholder masses exceed evaluable masses")
    loadable = _nonnegative_field(record, "loadable_collision_element_count", label)
    analytic = _nonnegative_field(record, "analytic_collision_element_count", label)
    if analytic > loadable:
        raise VerificationError(f"{label} analytic collision elements exceed loadable elements")
    _nonnegative_field(record, "collision_shape_count", label)
    _nonnegative_field(record, "collision_mesh_triangle_count", label)
    redundant = _expect_number(record.get("intra_link_redundant_volume_m3"), f"{label}.redundant volume", allow_negative=False)
    total = _expect_number(record.get("intra_link_shape_volume_m3"), f"{label}.shape volume", allow_negative=False)
    if redundant > total + 1e-15:
        raise VerificationError(f"{label} redundant volume exceeds total shape volume")
    _measurement(record, "collision_load_time_seconds", label, allow_negative=False)
    _measurement(record, "visual_to_collision_p95_normalized", label, allow_negative=False)
    _measurement(record, "collision_to_visual_p95_normalized", label, allow_negative=False)
    _measurement(record, "shapes_per_visual_bearing_link", label, allow_negative=False)
    _measurement(record, "collision_mesh_triangles_per_asset", label, allow_negative=False)
    _redundancy_measurement(record, label)


def _measurement(
    record: Mapping[str, Any], field: str, label: str, *, allow_negative: bool
) -> tuple[str, float | None, str | None]:
    """Read one per-asset measurement in scalar or {status,value,reason} form."""

    if field not in record:
        raise VerificationError(f"{label} lacks required {field}")
    raw = record[field]
    if isinstance(raw, dict):
        status = raw.get("status")
        value = raw.get("value")
        reason = raw.get("reason")
    else:
        status = record.get(f"{field}_status", "COMPLETE" if raw is not None else "N/E")
        value = raw
        reason = record.get(f"{field}_reason")
    if not isinstance(status, str) or status not in {"COMPLETE", "N/E", "FAILED", "UNMEASURED"}:
        raise VerificationError(f"{label}.{field} has invalid per-asset status {status!r}")
    if status == "COMPLETE":
        return status, _expect_number(value, f"{label}.{field}", allow_negative=allow_negative), None
    if value is not None:
        raise VerificationError(f"{label}.{field} must be null when status is {status}")
    if not isinstance(reason, str) or not reason.strip():
        raise VerificationError(f"{label}.{field} {status} requires a reason")
    return status, None, reason


def _redundancy_measurement(
    record: Mapping[str, Any], label: str
) -> tuple[str, float | None, float | None, int, int]:
    raw = _expect_dict(record.get("intra_link_redundancy"), f"{label}.intra_link_redundancy")
    status = raw.get("status")
    if status not in {"COMPLETE", "PARTIAL", "N/E"}:
        raise VerificationError(f"{label}.intra_link_redundancy has invalid status {status!r}")
    measured = _expect_int(
        _value_from_any(
            raw, ("measured_links", "measured_link_count"), "redundancy measured links"
        ),
        f"{label}.redundancy.measured_links",
        minimum=0,
    )
    intended = _expect_int(
        _value_from_any(
            raw, ("intended_links", "intended_link_count"), "redundancy intended links"
        ),
        f"{label}.redundancy.intended_links",
        minimum=0,
    )
    if measured > intended:
        raise VerificationError(f"{label}.redundancy measured links exceed intended links")
    value = raw.get("value")
    redundant = raw.get("redundant_volume_m3")
    shape = raw.get("shape_volume_m3")
    if status == "N/E":
        if measured != 0 or any(candidate is not None for candidate in (value, redundant, shape)):
            raise VerificationError(f"{label}.redundancy N/E must not contain a numeric result")
        _nonempty_reason(raw, f"{label}.intra_link_redundancy")
        return status, None, None, measured, intended

    if measured == 0 or intended == 0:
        raise VerificationError(f"{label}.redundancy {status} requires measured links")
    if status == "COMPLETE" and measured != intended:
        raise VerificationError(f"{label}.redundancy COMPLETE lacks complete link coverage")
    if status == "PARTIAL" and measured >= intended:
        raise VerificationError(f"{label}.redundancy PARTIAL has complete link coverage")
    redundant_value = _expect_number(
        redundant, f"{label}.redundancy.redundant_volume_m3", allow_negative=False
    )
    shape_value = _expect_number(shape, f"{label}.redundancy.shape_volume_m3", allow_negative=False)
    if shape_value <= 0.0 or redundant_value > shape_value + 1e-15:
        raise VerificationError(f"{label}.redundancy volumes are inconsistent")
    ratio = _expect_number(value, f"{label}.redundancy.value", allow_negative=False)
    expected_ratio = redundant_value / shape_value
    if not math.isclose(ratio, expected_ratio, rel_tol=1e-12, abs_tol=1e-15):
        raise VerificationError(f"{label}.redundancy value is not volume weighted")
    _require_same(
        record.get("intra_link_redundant_volume_m3"),
        redundant_value,
        f"{label}.intra_link_redundant_volume_m3 alias",
    )
    _require_same(
        record.get("intra_link_shape_volume_m3"),
        shape_value,
        f"{label}.intra_link_shape_volume_m3 alias",
    )
    return status, redundant_value, shape_value, measured, intended


def _validate_asset_records(
    rows: list[dict[str, Any]], items: Mapping[int, dict[str, Any]], protocol_id: str, config: VerifierConfig
) -> dict[int, dict[str, Any]]:
    if len(rows) != config.sample_size:
        raise VerificationError(f"asset_records row count {len(rows)} is not N={config.sample_size}")
    _ordered_rows(rows, lambda row: _expect_int(row.get("selection_rank"), "asset selection_rank", minimum=1), "asset_records")
    records: dict[int, dict[str, Any]] = {}
    keys: set[str] = set()
    for row in rows:
        _terminal(row, "asset record")
        rank = _expect_int(row.get("selection_rank"), "asset selection_rank", minimum=1)
        item = items.get(rank)
        if item is None or rank in records:
            raise VerificationError("asset record has duplicate or unknown selection_rank")
        key = row.get("asset_key")
        if not isinstance(key, str) or key in keys:
            raise VerificationError("asset record has missing or duplicate asset_key")
        for field in ("asset_key", "selection_rank", "input_identity_sha256", "source_record_sha256"):
            _require_same(row.get(field), item.get(field), f"asset record {field} rank {rank}")
        _require_same(row.get("protocol_id"), protocol_id, f"asset record protocol rank {rank}")
        _expect_bool(row.get("evaluation_success"), f"asset record evaluation_success rank {rank}")
        _required_asset_counts(row, f"asset record rank {rank}")
        for field in (
            "release_receipt_bound",
            "release_receipt_replay_pass",
            "deterministic_rebuild_eligible",
            "deterministic_rebuild_match",
            "strict_collision_pass_no_method_allowance",
            "strict_collision_pass_registered_allowance",
        ):
            _expect_bool(row.get(field), f"asset record {field} rank {rank}")
        _nonnegative_field(row, "eligible_non_adjacent_pair_count", f"asset record rank {rank}")
        _nonnegative_field(row, "registered_method_allowance_pair_count", f"asset record rank {rank}")
        if row.get("release_receipt_bound") or row.get("release_receipt_replay_pass"):
            raise VerificationError("LAM release receipt result may not be sourced from this evaluator")
        if row.get("deterministic_rebuild_eligible") or row.get("deterministic_rebuild_match"):
            raise VerificationError("LAM has no frozen release build recipe; deterministic rebuild must be N/E")
        if row.get("registered_method_allowance_pair_count") != 0:
            raise VerificationError("LAM allowance registry is empty; per-asset allowance count must be zero")
        _require_same(
            row.get("strict_collision_pass_registered_allowance"),
            row.get("strict_collision_pass_no_method_allowance"),
            "empty-allowance strict-pass equivalence",
        )
        records[rank] = row
        keys.add(key)
    if set(records) != set(range(1, config.sample_size + 1)):
        raise VerificationError("asset records do not cover exactly ranks 1..N")
    return records


def _joint_key(row: Mapping[str, Any]) -> tuple[str, str]:
    asset_key = row.get("asset_key")
    joint_name = row.get("joint_name")
    if not isinstance(asset_key, str) or not asset_key or not isinstance(joint_name, str) or not joint_name:
        raise VerificationError("joint record lacks asset_key or joint_name")
    return asset_key, joint_name


def _bounded_source_joint(source_joint: Mapping[str, Any]) -> bool:
    return source_joint.get("joint_type") != "continuous"


def _validate_joint_records(
    rows: list[dict[str, Any]],
    source: SourceCohort,
    items: Mapping[int, dict[str, Any]],
    protocol_id: str,
    config: VerifierConfig,
) -> dict[tuple[str, str], dict[str, Any]]:
    if len(rows) != config.joint_count:
        raise VerificationError(f"joint_records row count {len(rows)} is not J={config.joint_count}")
    _ordered_rows(
        rows,
        lambda row: source.joint_order.get(_joint_key(row), config.joint_count + 1),
        "joint_records",
    )
    records: dict[tuple[str, str], dict[str, Any]] = {}
    for row in rows:
        _terminal(row, "joint record")
        key = _joint_key(row)
        source_joint = source.joints_by_key.get(key)
        if source_joint is None or key in records:
            raise VerificationError(f"joint record has duplicate or unknown frozen joint {key!r}")
        asset_key, _ = key
        rank = _expect_int(row.get("selection_rank"), "joint selection_rank", minimum=1)
        item = items.get(rank)
        if item is None or item.get("asset_key") != asset_key:
            raise VerificationError(f"joint record rank/asset binding mismatch for {key!r}")
        for field in ("protocol_id", "input_identity_sha256"):
            expected = protocol_id if field == "protocol_id" else item.get(field)
            _require_same(row.get(field), expected, f"joint record {field} {key!r}")
        _require_same(
            _expect_bool(row.get("table3_joint_pass"), f"joint table3 pass {key!r}"),
            bool(source_joint.get("joint_level_pass")),
            f"joint Table-3 pass binding {key!r}",
        )
        _require_same(
            _expect_int(row.get("intended_state_count"), f"joint intended states {key!r}", minimum=0),
            STATE_SAMPLES_PER_JOINT,
            f"joint frozen intended-state count {key!r}",
        )
        executed = _expect_int(row.get("executed_state_count"), f"joint executed states {key!r}", minimum=0)
        if executed > STATE_SAMPLES_PER_JOINT:
            raise VerificationError(f"joint executed states exceed K for {key!r}")
        _expect_bool(row.get("full_range_cf_pass"), f"joint full_range_cf_pass {key!r}")
        _expect_bool(row.get("joint_limit_portable"), f"joint_limit_portable {key!r}")
        _expect_bool(row.get("dynamics_present"), f"dynamics_present {key!r}")
        bounded = _expect_bool(row.get("bounded"), f"bounded {key!r}")
        _require_same(bounded, _bounded_source_joint(source_joint), f"joint bounded binding {key!r}")
        reachable = row.get("limit_reachable")
        if bounded:
            _expect_bool(reachable, f"limit_reachable {key!r}")
        elif reachable is not None:
            raise VerificationError(f"continuous joint limit_reachable must be null for {key!r}")
        records[key] = row
    if set(records) != set(source.joints_by_key):
        raise VerificationError("joint records do not close against all frozen Table-3 joints")
    return records


